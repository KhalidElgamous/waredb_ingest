"""Declarative base shared by all ORM models.

``Base`` owns a single ``MetaData`` instance, so every model that subclasses it
lands in one metadata collection: the one Alembic compares against the database
when autogenerating migrations.

The metadata carries a naming convention, so primary keys, foreign keys, unique
constraints and indexes get predictable names (``pk_user``,
``fk_chunk_fact_document_id``, ...). Named constraints can later be altered or
dropped by name on any database, and autogenerated migrations stay stable.
"""

from sqlalchemy import MetaData
from sqlalchemy.ext.declarative import declarative_base

NAMING_CONVENTION = {
  "ix": "ix_%(column_0_label)s",
  "uq": "uq_%(table_name)s_%(column_0_N_name)s",
  "ck": "ck_%(table_name)s_%(constraint_name)s",
  "fk": "fk_%(table_name)s_%(column_0_name)s",
  "pk": "pk_%(table_name)s",
}

Base = declarative_base(metadata=MetaData(naming_convention=NAMING_CONVENTION))
